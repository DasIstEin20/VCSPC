const VcsScmSaContract* VcsScmSaFindContract(unsigned short opcode)
{
    unsigned int first = 0;
    unsigned int last = sizeof(contracts) / sizeof(contracts[0]);
    while (first < last) {
        const unsigned int middle = first + (last - first) / 2;
        if (contracts[middle].opcode < opcode) first = middle + 1;
        else last = middle;
    }
    return first < sizeof(contracts) / sizeof(contracts[0]) && contracts[first].opcode == opcode ?
        &contracts[first] : nullptr;
}
